-- setup_brush.sql — قسم البرشر (بطلبيات + وردية + هالك جودة + شغل بدون إنترنت)
-- شغّله مرة واحدة من Supabase -> SQL Editor -> New query -> Run (آمن لو اتشغّل أكتر من مرة)
-- محتاج setup_v2.sql و setup_security.sql و setup_order_groups.sql يكونوا اتشغّلوا قبله.
-- بعده: شغّل setup_backup.sql و setup_search.sql تاني (عشان النسخ الاحتياطي والبحث يشملوا البرشر).
-- نسخة موحّدة من تطوّر الصب اليدوي (setup_casting.sql → v5) بعد التجميع.
-- =====================================================================

-- 1) جدول طلبيات البرشر (كل صنف سطر واحد، مربوط بالطلبية الرئيسية order_groups)
create table if not exists public.brush_orders (
  id           bigint generated by default as identity primary key,
  title        text   check (title is null or char_length(title) <= 120),
  item         text   not null check (char_length(item) between 1 and 120),
  qty_required integer not null check (qty_required > 0 and qty_required <= 1000000),
  order_date   date   not null default current_date,
  due_date     date,
  status       text   not null default 'open' check (status in ('open','done')),
  note         text   check (note is null or char_length(note) <= 300),
  group_id     uuid   references public.order_groups(id) on delete cascade,
  created_by   uuid   default auth.uid(),
  created_at   timestamptz not null default now()
);
create index if not exists brush_orders_status_idx on public.brush_orders (status);
create index if not exists brush_orders_group_idx  on public.brush_orders (group_id);

-- 2) جدول سجل البرشر
create table if not exists public.brush_log (
  id          bigint generated by default as identity primary key,
  brush_date  date        not null default current_date,
  item        text,
  qty         integer     not null default 0,
  scrap       integer     not null default 0,
  shift       text,
  worker      text        check (worker is null or char_length(worker) <= 80),
  note        text        check (note   is null or char_length(note)   <= 300),
  order_id    bigint      references public.brush_orders(id) on delete set null,
  client_id   uuid,
  created_by  uuid        default auth.uid(),
  created_at  timestamptz not null default now(),
  constraint brush_log_shift_chk check (shift is null or shift in ('صباحي','مسائي','ليلي')),
  constraint brush_log_scrap_chk check (scrap >= 0 and scrap <= 100000),
  -- عدد القطع ممكن يبقى 0 لو التسجيل كله هالك (بشرط إن القطع + الهالك أكبر من صفر)
  constraint brush_log_qty_scrap_chk check (qty >= 0 and qty <= 100000 and qty + scrap > 0)
);
create index if not exists brush_log_date_idx  on public.brush_log (brush_date);
create index if not exists brush_log_order_idx on public.brush_log (order_id);
-- client_id: عشان تسجيل البرشر اللي اتحفظ على الجهاز من غير نت ما يتكررش لو اتبعت مرتين
create unique index if not exists brush_log_client_id_uidx on public.brush_log (client_id) where client_id is not null;

-- 3) الأمان (RLS)
alter table public.brush_orders enable row level security;
alter table public.brush_log    enable row level security;

-- طلبيات البرشر: القراءة لأعضاء القسم والموظفين، والتعديل لمسؤول القسم وأي مدير (توزيع الطلبيات)
drop policy if exists bo_select on public.brush_orders;
drop policy if exists bo_insert on public.brush_orders;
drop policy if exists bo_update on public.brush_orders;
drop policy if exists bo_delete on public.brush_orders;
create policy bo_select on public.brush_orders for select to authenticated
  using ((select public.can_section('brush')) or (select public.is_staff()));
create policy bo_insert on public.brush_orders for insert to authenticated
  with check ((select public.can_manage_section('brush')) or (select public.is_manager_any()));
create policy bo_update on public.brush_orders for update to authenticated
  using ((select public.can_manage_section('brush')) or (select public.is_manager_any()))
  with check ((select public.can_manage_section('brush')) or (select public.is_manager_any()));
create policy bo_delete on public.brush_orders for delete to authenticated
  using ((select public.can_manage_section('brush')) or (select public.is_manager_any()));

-- سجل البرشر: القراءة والإضافة لأعضاء القسم.
-- التعديل والحذف: المدير ومسؤول القسم في أي وقت، ومسجّل الإنتاج في تسجيلاته هو وفي نفس اليوم بس.
drop policy if exists brush_select on public.brush_log;
drop policy if exists brush_insert on public.brush_log;
drop policy if exists brush_update on public.brush_log;
drop policy if exists brush_delete on public.brush_log;
create policy brush_select on public.brush_log for select to authenticated
  using ((select public.can_section('brush')));
create policy brush_insert on public.brush_log for insert to authenticated
  with check (
    (select public.can_section('brush'))
    and (created_by is null or created_by = auth.uid())
    and ((select public.can_manage_section('brush'))
         or brush_date = left(public.server_today()::text, 10)::date)
  );
create policy brush_update on public.brush_log for update to authenticated
  using (
    (select public.can_manage_section('brush'))
    or ((select public.can_section('brush')) and created_by = auth.uid()
        and brush_date = left(public.server_today()::text, 10)::date)
  )
  with check (
    (select public.can_manage_section('brush'))
    or ((select public.can_section('brush')) and created_by = auth.uid()
        and brush_date = left(public.server_today()::text, 10)::date)
  );
create policy brush_delete on public.brush_log for delete to authenticated
  using (
    (select public.can_manage_section('brush'))
    or ((select public.can_section('brush')) and created_by = auth.uid()
        and brush_date = left(public.server_today()::text, 10)::date)
  );

revoke all on public.brush_orders from anon;
revoke all on public.brush_log    from anon;
grant select, insert, update, delete on public.brush_orders to authenticated;
grant select, insert, update, delete on public.brush_log    to authenticated;

-- 4) عرض (view) إنجاز طلبيات البرشر: المطلوب والمنتج لكل طلبية (بيستخدمه لوحة الرئيسية وتوقّع التأخير)
create or replace view public.brush_status with (security_invoker = true) as
select o.id, o.item, o.status, o.order_date, o.due_date, o.group_id, o.qty_required,
       coalesce(sum(l.qty), 0)::integer as produced
  from public.brush_orders o
  left join public.brush_log l on l.order_id = o.id
 group by o.id;
revoke all on public.brush_status from anon;
grant select on public.brush_status to authenticated;

-- 5) حالة الطلبية بتتظبط أوتوماتيك من الإنتاج المسجّل (مفتوحة / مكتملة)
--    security definer عشان مسجّل الإنتاج (اللي ملوش صلاحية تعديل الطلبيات) تتحدّث الحالة برضو
create or replace function public.brush_sync_status(p_id bigint)
returns void language plpgsql security definer set search_path = public as $$
declare v_req integer; v_done integer;
begin
  if p_id is null then return; end if;
  select qty_required into v_req from public.brush_orders where id = p_id;
  if v_req is null then return; end if;
  select coalesce(sum(qty), 0) into v_done from public.brush_log where order_id = p_id;
  update public.brush_orders
     set status = case when v_done >= v_req then 'done' else 'open' end
   where id = p_id and status is distinct from (case when v_done >= v_req then 'done' else 'open' end);
end $$;
revoke all on function public.brush_sync_status(bigint) from public;

create or replace function public.brush_log_after()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE','DELETE') then perform public.brush_sync_status(old.order_id); end if;
  if tg_op in ('INSERT','UPDATE') then perform public.brush_sync_status(new.order_id); end if;
  return null;
end $$;
revoke all on function public.brush_log_after() from public;

drop trigger if exists trg_brush_log_sync on public.brush_log;
create trigger trg_brush_log_sync after insert or update of qty, order_id or delete
  on public.brush_log for each row execute function public.brush_log_after();

-- لما المدير يغيّر الصنف أو الكمية المطلوبة في صفحة الطلبيات: الحالة تتظبط واسم الصنف يتعدّل في التسجيلات المربوطة
create or replace function public.brush_order_after()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.item is distinct from old.item then
    update public.brush_log set item = new.item where order_id = new.id;
  end if;
  if new.qty_required is distinct from old.qty_required then
    perform public.brush_sync_status(new.id);
  end if;
  return null;
end $$;
revoke all on function public.brush_order_after() from public;

drop trigger if exists trg_brush_order_sync on public.brush_orders;
create trigger trg_brush_order_sync after update of item, qty_required
  on public.brush_orders for each row execute function public.brush_order_after();

-- 6) سجل النشاط: ننسخ نفس الـ triggers اللي على repair_log (لو موجودة) عشان عمليات البرشر تظهر في «سجل النشاط»
do $$
declare r record; def text; t text;
begin
  if to_regclass('public.repair_log') is null then return; end if;
  foreach t in array array['brush_log','brush_orders'] loop
    for r in
      select g.tgname, pg_get_triggerdef(g.oid) as d
        from pg_trigger g
       where g.tgrelid = 'public.repair_log'::regclass and not g.tgisinternal
    loop
      def := replace(r.d, 'repair_log', t);
      execute format('drop trigger if exists %I on public.%I', replace(r.tgname, 'repair_log', t), t);
      execute def;
    end loop;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

notify pgrst, 'reload schema';

