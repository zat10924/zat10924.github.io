-- =====================================================================
-- setup_firing.sql — قسم الحريق (شحن وحريق عربيات البسكوت والجليز + صور العداد)
-- شغّله مرة واحدة من Supabase -> SQL Editor -> New query -> Run (آمن لو اتشغّل أكتر من مرة).
-- محتاج setup_v2.sql و setup_security.sql و setup_roles_v2.sql يكونوا اتشغّلوا قبله (فيهم can_section و can_manage_section).
-- (مش محتاج تعديل في باقي ملفات SQL: صاحب المصنع والمدير اللي «يشوف باقي الأقسام» مغطّيين جوه الملف ده.)
--
-- التصميم:
--   firing_kilns          بيانات الأفران
--   firing_loads          سجل شحن العربية (kind = biscuit | glaze)  — قيد التجهيز (draft) ثم معتمد (approved)
--   firing_load_items     الأصناف والكميات داخل كل عربية
--   firing_operations     عمليات الحريق (قيد التجهيز / داخل الفرن / مكتملة) مربوطة بعربية وفرن
--   firing_meter_photos   صور العداد (المسار في Storage فقط، مش الصورة نفسها) — الصور القديمة بتتحفظ ومبتتمسحش
--
-- الكتابة كلها بتم من خلال دوال (RPC) بتتحقق من الصلاحيات والقواعد وبتحفظ كل عملية في معاملة واحدة.
-- الجداول للقراءة فقط من الواجهة. مفيش حذف للبيانات التاريخية: العمليات المكتملة والصور بتفضل.
-- لا بيخصم ولا بيضيف مخزون، ولا بينقل كميات بين المراحل.
-- =====================================================================

-- ---------- 0) دوال مساعدة (آمنة لو موجودة) ----------
create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p
    where p.id = auth.uid() and coalesce(p.active, true) and p.role = 'owner');
$$;
revoke all on function public.is_owner() from public;
grant execute on function public.is_owner() to authenticated;

alter table public.profiles add column if not exists view_all boolean not null default false;
create or replace function public.can_view_all()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p
    where p.id = auth.uid() and coalesce(p.active, true) and p.role = 'manager' and coalesce(p.view_all, false));
$$;
revoke all on function public.can_view_all() from public;
grant execute on function public.can_view_all() to authenticated;

-- ---------- 1) الجداول ----------
create table if not exists public.firing_kilns (
  id         bigint generated by default as identity primary key,
  name       text   not null check (char_length(btrim(name)) between 1 and 60),
  note       text   check (note is null or char_length(note) <= 200),
  active     boolean not null default true,
  created_by uuid   default auth.uid(),
  created_at timestamptz not null default now()
);
create unique index if not exists firing_kilns_name_uidx on public.firing_kilns (lower(btrim(name)));

create table if not exists public.firing_loads (
  id              bigint generated by default as identity primary key,
  kind            text   not null check (kind in ('biscuit','glaze')),
  cart_code       text   not null check (char_length(btrim(cart_code)) between 1 and 60),
  loaded_at       timestamptz not null default now(),
  worker          text   check (worker is null or char_length(worker) <= 80),
  note            text   check (note is null or char_length(note) <= 300),
  status          text   not null default 'draft' check (status in ('draft','approved')),
  total_qty       integer not null default 0 check (total_qty >= 0),
  approved_at     timestamptz,
  approved_by     uuid,
  approved_by_name text,
  created_by      uuid   default auth.uid(),
  created_by_name text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists firing_loads_kind_idx   on public.firing_loads (kind, loaded_at desc);
create index if not exists firing_loads_status_idx on public.firing_loads (status);

create table if not exists public.firing_load_items (
  id      bigint generated by default as identity primary key,
  load_id bigint  not null references public.firing_loads(id) on delete cascade,
  item    text    not null check (char_length(btrim(item)) between 1 and 120),
  qty     integer not null check (qty > 0 and qty <= 1000000),
  sort    smallint not null default 0
);
create index if not exists firing_load_items_load_idx on public.firing_load_items (load_id);

create table if not exists public.firing_operations (
  id               bigint generated by default as identity primary key,
  kind             text   not null check (kind in ('biscuit','glaze')),
  load_id          bigint not null references public.firing_loads(id) on delete restrict,
  kiln_id          bigint not null references public.firing_kilns(id) on delete restrict,
  status           text   not null default 'preparing' check (status in ('preparing','in_kiln','done')),
  entered_at       timestamptz,
  finished_at      timestamptz,
  tubes_used       integer check (tubes_used is null or (tubes_used >= 0 and tubes_used <= 100000)),
  worker           text   not null check (char_length(btrim(worker)) between 1 and 80),
  created_by       uuid   default auth.uid(),
  created_by_name  text,
  finished_by      uuid,
  finished_by_name text,
  photo_count      integer not null default 0,
  last_photo_at    timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint firing_ops_state_chk check (
       (status = 'preparing' and entered_at is null  and finished_at is null)
    or (status = 'in_kiln'   and entered_at is not null and finished_at is null)
    or (status = 'done'      and entered_at is not null and finished_at is not null and tubes_used is not null)),
  constraint firing_ops_time_chk check (finished_at is null or finished_at >= entered_at)
);
-- العربية بتتحرق مرة واحدة بس، والفرن مفيهوش غير عملية واحدة «داخل الفرن» في نفس الوقت
create unique index if not exists firing_ops_load_uidx   on public.firing_operations (load_id);
create unique index if not exists firing_ops_kiln_active on public.firing_operations (kiln_id) where status = 'in_kiln';
create index if not exists firing_ops_status_idx on public.firing_operations (kind, status, entered_at desc);

create table if not exists public.firing_meter_photos (
  id               bigint generated by default as identity primary key,
  operation_id     bigint not null references public.firing_operations(id) on delete restrict,
  storage_path     text   not null unique,
  taken_at         timestamptz not null default now(),   -- بيتسجل تلقائي من السيرفر وقت الرفع
  size_bytes       integer check (size_bytes is null or size_bytes >= 0),
  uploaded_by      uuid   default auth.uid(),
  uploaded_by_name text,
  replaces_id      bigint references public.firing_meter_photos(id) on delete restrict,
  replaced_by      bigint references public.firing_meter_photos(id) on delete restrict,
  created_at       timestamptz not null default now()
);
create index if not exists firing_photos_op_idx on public.firing_meter_photos (operation_id, taken_at);

-- ---------- 2) الأمان (RLS): قراءة فقط من الواجهة ----------
alter table public.firing_kilns         enable row level security;
alter table public.firing_loads         enable row level security;
alter table public.firing_load_items    enable row level security;
alter table public.firing_operations    enable row level security;
alter table public.firing_meter_photos  enable row level security;

do $$
declare t text;
begin
  foreach t in array array['firing_kilns','firing_loads','firing_load_items','firing_operations','firing_meter_photos'] loop
    execute format('drop policy if exists fire_select on public.%I', t);
    execute format('create policy fire_select on public.%I for select to authenticated using ((select public.can_section(%L)) or (select public.can_view_all()))', t, 'fire');
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke insert, update, delete on public.%I from authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
  end loop;
end $$;

-- ---------- 3) دوال داخلية ----------
create or replace function public.firing_user_name() returns text
language sql stable security definer set search_path = public as $$
  select coalesce(nullif(btrim(p.full_name), ''), nullif(btrim(p.email), ''), 'مستخدم')
    from public.profiles p where p.id = auth.uid();
$$;
revoke all on function public.firing_user_name() from public;

create or replace function public.firing_assert_write() returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if auth.uid() is null or not (select public.can_section('fire')) then
    raise exception 'not allowed';
  end if;
  if (select public.is_owner()) then
    raise exception 'owner read only';
  end if;
end $$;
revoke all on function public.firing_assert_write() from public;

-- المدير ومسؤول القسم، أو صاحب السجل نفسه
create or replace function public.firing_can_edit_row(p_creator uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select (select public.can_manage_section('fire')) or p_creator = auth.uid();
$$;
revoke all on function public.firing_can_edit_row(uuid) from public;

-- ---------- 4) الأفران (للمدير ومسؤول القسم) ----------
create or replace function public.firing_save_kiln(p_id bigint, p_name text, p_note text, p_active boolean)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_name text := btrim(coalesce(p_name, ''));
begin
  perform public.firing_assert_write();
  if not (select public.can_manage_section('fire')) then raise exception 'not allowed'; end if;
  if char_length(v_name) < 1 or char_length(v_name) > 60 then raise exception 'invalid kiln name'; end if;
  if p_id is null then
    insert into public.firing_kilns(name, note, active) values (v_name, nullif(btrim(coalesce(p_note,'')), ''), coalesce(p_active, true))
    returning id into v_id;
  else
    if p_active is false and exists (select 1 from public.firing_operations where kiln_id = p_id and status = 'in_kiln') then
      raise exception 'kiln busy';
    end if;
    update public.firing_kilns set name = v_name, note = nullif(btrim(coalesce(p_note,'')), ''), active = coalesce(p_active, true)
     where id = p_id returning id into v_id;
    if v_id is null then raise exception 'kiln not found'; end if;
  end if;
  return v_id;
exception when unique_violation then
  raise exception 'kiln name exists';
end $$;
revoke all on function public.firing_save_kiln(bigint, text, text, boolean) from public;
grant execute on function public.firing_save_kiln(bigint, text, text, boolean) to authenticated;

-- ---------- 5) شحن العربية (إنشاء/تعديل مسودة + اعتماد اختياري) في معاملة واحدة ----------
-- p_items: [{"item":"اسم الصنف","qty":10}, ...] — الأصناف لازم تكون من الأصناف المسجلة في النظام (catalog)
create or replace function public.firing_save_load(
  p_id bigint, p_kind text, p_cart text, p_loaded_at timestamptz,
  p_worker text, p_note text, p_items jsonb, p_approve boolean default false)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_id bigint; v_row public.firing_loads%rowtype; v_cart text := btrim(coalesce(p_cart, ''));
  v_at timestamptz := coalesce(p_loaded_at, now()); v_el jsonb; v_name text; v_qty integer;
  v_total integer := 0; v_n integer := 0; v_me text := public.firing_user_name();
  v_sum jsonb := '{}'::jsonb;
begin
  perform public.firing_assert_write();
  if p_id is null and p_kind not in ('biscuit','glaze') then raise exception 'invalid kind'; end if;
  if char_length(v_cart) < 1 or char_length(v_cart) > 60 then raise exception 'cart code required'; end if;
  if v_at > now() + interval '10 minutes' then raise exception 'future time'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 60 then
    raise exception 'items required';
  end if;

  if p_id is not null then
    select * into v_row from public.firing_loads where id = p_id for update;
    if not found then raise exception 'load not found'; end if;
    if v_row.status <> 'draft' then raise exception 'load locked'; end if;
    if not public.firing_can_edit_row(v_row.created_by) then raise exception 'not allowed'; end if;
  end if;

  -- تجميع الأصناف المتكررة وفحص إنها مسجّلة وفحص الكميات
  for v_el in select * from jsonb_array_elements(p_items) loop
    begin v_qty := (v_el->>'qty')::integer; exception when others then raise exception 'invalid qty'; end;
    if v_qty is null or v_qty < 1 or v_qty > 1000000 then raise exception 'invalid qty'; end if;
    select c.name into v_name from public.catalog c
     where c.kind = 'item' and lower(btrim(c.name)) = lower(btrim(coalesce(v_el->>'item', '')))
     limit 1;
    if v_name is null then raise exception 'unknown item'; end if;
    v_sum := jsonb_set(v_sum, array[v_name], to_jsonb(coalesce((v_sum->>v_name)::integer, 0) + v_qty));
  end loop;

  if p_id is null then
    insert into public.firing_loads(kind, cart_code, loaded_at, worker, note, created_by_name)
    values (p_kind, v_cart, v_at, nullif(btrim(coalesce(p_worker,'')), ''), nullif(btrim(coalesce(p_note,'')), ''), v_me)
    returning id into v_id;
  else
    v_id := p_id;
    update public.firing_loads
       set cart_code = v_cart, loaded_at = v_at, worker = nullif(btrim(coalesce(p_worker,'')), ''),
           note = nullif(btrim(coalesce(p_note,'')), ''), updated_at = now()
     where id = v_id;
    delete from public.firing_load_items where load_id = v_id;   -- المسودة فقط (لسه ما اتعتمدتش)
  end if;

  for v_name in select jsonb_object_keys(v_sum) loop
    v_n := v_n + 1;
    insert into public.firing_load_items(load_id, item, qty, sort) values (v_id, v_name, (v_sum->>v_name)::integer, v_n);
    v_total := v_total + (v_sum->>v_name)::integer;
  end loop;
  update public.firing_loads set total_qty = v_total where id = v_id;

  if coalesce(p_approve, false) then
    update public.firing_loads set status = 'approved', approved_at = now(), approved_by = auth.uid(), approved_by_name = v_me where id = v_id;
  end if;
  return v_id;
end $$;
revoke all on function public.firing_save_load(bigint, text, text, timestamptz, text, text, jsonb, boolean) from public;
grant execute on function public.firing_save_load(bigint, text, text, timestamptz, text, text, jsonb, boolean) to authenticated;

create or replace function public.firing_approve_load(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_row public.firing_loads%rowtype;
begin
  perform public.firing_assert_write();
  select * into v_row from public.firing_loads where id = p_id for update;
  if not found then raise exception 'load not found'; end if;
  if v_row.status <> 'draft' then raise exception 'load locked'; end if;
  if not public.firing_can_edit_row(v_row.created_by) then raise exception 'not allowed'; end if;
  if not exists (select 1 from public.firing_load_items where load_id = p_id) then raise exception 'items required'; end if;
  update public.firing_loads set status = 'approved', approved_at = now(), approved_by = auth.uid(),
         approved_by_name = public.firing_user_name(), updated_at = now() where id = p_id;
end $$;
revoke all on function public.firing_approve_load(bigint) from public;
grant execute on function public.firing_approve_load(bigint) to authenticated;

