-- ---------- 6) بدء الحريق ----------
-- p_entered = null  => «قيد التجهيز» (العربية لسه ما دخلتش الفرن)
create or replace function public.firing_start(p_load bigint, p_kiln bigint, p_entered timestamptz, p_worker text)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_load public.firing_loads%rowtype; v_kiln public.firing_kilns%rowtype; v_id bigint; v_w text := btrim(coalesce(p_worker, ''));
begin
  perform public.firing_assert_write();
  select * into v_load from public.firing_loads where id = p_load for update;
  if not found then raise exception 'load not found'; end if;
  if v_load.status <> 'approved' then raise exception 'load not approved'; end if;
  if exists (select 1 from public.firing_operations where load_id = p_load) then raise exception 'load already fired'; end if;
  select * into v_kiln from public.firing_kilns where id = p_kiln;
  if not found or not v_kiln.active then raise exception 'kiln not found'; end if;
  if char_length(v_w) < 1 then raise exception 'worker required'; end if;
  if p_entered is not null then
    if p_entered > now() + interval '10 minutes' then raise exception 'future time'; end if;
    if p_entered < v_load.loaded_at then raise exception 'entered before loaded'; end if;
    if exists (select 1 from public.firing_operations where kiln_id = p_kiln and status = 'in_kiln') then raise exception 'kiln busy'; end if;
  end if;
  insert into public.firing_operations(kind, load_id, kiln_id, status, entered_at, worker, created_by_name)
  values (v_load.kind, p_load, p_kiln, case when p_entered is null then 'preparing' else 'in_kiln' end, p_entered, v_w, public.firing_user_name())
  returning id into v_id;
  return v_id;
exception when unique_violation then
  raise exception 'kiln busy';
end $$;
revoke all on function public.firing_start(bigint, bigint, timestamptz, text) from public;
grant execute on function public.firing_start(bigint, bigint, timestamptz, text) to authenticated;

-- دخول العربية للفرن (من «قيد التجهيز» إلى «داخل الفرن»)
create or replace function public.firing_enter(p_op bigint, p_entered timestamptz, p_kiln bigint default null)
returns void language plpgsql security definer set search_path = public as $$
declare v_op public.firing_operations%rowtype; v_load public.firing_loads%rowtype; v_at timestamptz := coalesce(p_entered, now());
begin
  perform public.firing_assert_write();
  select * into v_op from public.firing_operations where id = p_op for update;
  if not found then raise exception 'operation not found'; end if;
  if v_op.status <> 'preparing' then raise exception 'invalid state'; end if;
  select * into v_load from public.firing_loads where id = v_op.load_id;
  if v_at > now() + interval '10 minutes' then raise exception 'future time'; end if;
  if v_at < v_load.loaded_at then raise exception 'entered before loaded'; end if;
  if p_kiln is not null and p_kiln <> v_op.kiln_id then
    if not exists (select 1 from public.firing_kilns where id = p_kiln and active) then raise exception 'kiln not found'; end if;
    update public.firing_operations set kiln_id = p_kiln where id = p_op;
  end if;
  update public.firing_operations set status = 'in_kiln', entered_at = v_at, updated_at = now() where id = p_op;
exception when unique_violation then
  raise exception 'kiln busy';
end $$;
revoke all on function public.firing_enter(bigint, timestamptz, bigint) from public;
grant execute on function public.firing_enter(bigint, timestamptz, bigint) to authenticated;

-- ---------- 7) إنهاء الحريق ----------
create or replace function public.firing_finish(p_op bigint, p_finished timestamptz, p_tubes integer)
returns void language plpgsql security definer set search_path = public as $$
declare v_op public.firing_operations%rowtype; v_at timestamptz := coalesce(p_finished, now());
begin
  perform public.firing_assert_write();
  select * into v_op from public.firing_operations where id = p_op for update;
  if not found then raise exception 'operation not found'; end if;
  if v_op.status <> 'in_kiln' or v_op.entered_at is null then raise exception 'not entered'; end if;
  if v_at > now() + interval '10 minutes' then raise exception 'future time'; end if;
  if v_at < v_op.entered_at then raise exception 'finish before entry'; end if;
  if p_tubes is null or p_tubes < 0 or p_tubes > 100000 then raise exception 'invalid tubes'; end if;
  update public.firing_operations
     set status = 'done', finished_at = v_at, tubes_used = p_tubes,
         finished_by = auth.uid(), finished_by_name = public.firing_user_name(), updated_at = now()
   where id = p_op;
end $$;
revoke all on function public.firing_finish(bigint, timestamptz, integer) from public;
grant execute on function public.firing_finish(bigint, timestamptz, integer) to authenticated;

-- ---------- 8) تسجيل صورة العداد (بعد نجاح الرفع على Storage) ----------
-- المسار لازم يبقى «رقم العملية/اسم الملف». لو p_replaces موجودة = إعادة رفع بدل صورة غلط (الأصلية بتفضل محفوظة)
create or replace function public.firing_add_photo(p_op bigint, p_path text, p_size integer, p_replaces bigint default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_op public.firing_operations%rowtype; v_id bigint; v_old public.firing_meter_photos%rowtype;
begin
  perform public.firing_assert_write();
  select * into v_op from public.firing_operations where id = p_op for update;
  if not found then raise exception 'operation not found'; end if;
  if v_op.status = 'preparing' then raise exception 'not entered'; end if;
  if v_op.status = 'done' and p_replaces is null then raise exception 'operation finished'; end if;
  if p_path is null or p_path !~ ('^' || p_op::text || '/[A-Za-z0-9._-]{1,120}$') then raise exception 'invalid path'; end if;
  if p_replaces is not null then
    select * into v_old from public.firing_meter_photos where id = p_replaces for update;
    if not found or v_old.operation_id <> p_op then raise exception 'photo not found'; end if;
    if v_old.replaced_by is not null then raise exception 'photo already replaced'; end if;
  end if;
  insert into public.firing_meter_photos(operation_id, storage_path, size_bytes, uploaded_by_name, replaces_id)
  values (p_op, p_path, p_size, public.firing_user_name(), p_replaces) returning id into v_id;
  if p_replaces is not null then
    update public.firing_meter_photos set replaced_by = v_id where id = p_replaces;
  end if;
  update public.firing_operations o
     set photo_count = (select count(*) from public.firing_meter_photos x where x.operation_id = p_op and x.replaced_by is null),
         last_photo_at = (select max(x.taken_at) from public.firing_meter_photos x where x.operation_id = p_op),
         updated_at = now()
   where o.id = p_op;
  return v_id;
end $$;
revoke all on function public.firing_add_photo(bigint, text, integer, bigint) from public;
grant execute on function public.firing_add_photo(bigint, text, integer, bigint) to authenticated;

-- ---------- 9) تخزين صور العداد (Supabase Storage) — خاص، مفيش وصول عام ----------
do $$
begin
  if to_regclass('storage.buckets') is null then
    raise notice 'Storage مش متاح: أنشئ bucket خاص اسمه firing-meters من لوحة Supabase';
    return;
  end if;
  insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
  values ('firing-meters', 'firing-meters', false, 5242880, array['image/jpeg','image/png','image/webp'])
  on conflict (id) do update set public = false, file_size_limit = 5242880,
        allowed_mime_types = array['image/jpeg','image/png','image/webp'];

  drop policy if exists firing_meters_select on storage.objects;
  drop policy if exists firing_meters_insert on storage.objects;
  drop policy if exists firing_meters_delete_orphan on storage.objects;

  -- القراءة: أعضاء قسم الحريق (والمدير وصاحب المصنع) ومسؤول القسم اللي «يشوف باقي الأقسام»
  create policy firing_meters_select on storage.objects for select to authenticated
    using (bucket_id = 'firing-meters' and ((select public.can_section('fire')) or (select public.can_view_all())));
  -- الرفع: أعضاء القسم (مش صاحب المصنع) وفي مجلد رقم العملية بس
  create policy firing_meters_insert on storage.objects for insert to authenticated
    with check (bucket_id = 'firing-meters' and (select public.can_section('fire')) and not (select public.is_owner())
                and (storage.foldername(name))[1] ~ '^[0-9]+$');
  -- مفيش تعديل ولا حذف للصور المسجّلة. الاستثناء الوحيد: ملف اترفع ومتسجّلش في الجدول (فشل وسط العملية) صاحبه يقدر يمسحه
  create policy firing_meters_delete_orphan on storage.objects for delete to authenticated
    using (bucket_id = 'firing-meters' and owner = auth.uid()
           and not exists (select 1 from public.firing_meter_photos p where p.storage_path = name));
end $$;

-- ---------- 10) سجل النشاط: ننسخ نفس الـ triggers اللي على repair_log (لو موجودة) ----------
do $$
declare r record; def text; t text;
begin
  if to_regclass('public.repair_log') is null then return; end if;
  foreach t in array array['firing_loads','firing_operations','firing_meter_photos'] loop
    for r in
      select g.tgname, pg_get_triggerdef(g.oid) as d
        from pg_trigger g
       where g.tgrelid = 'public.repair_log'::regclass and not g.tgisinternal
    loop
      def := replace(r.d, 'repair_log', t);
      execute format('drop trigger if exists %I on public.%I', replace(r.tgname, 'repair_log', t), t);
      execute def;
    end loop;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

