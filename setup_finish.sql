-- setup_finish.sql — قسم الفنش (تسجيل إنتاج بالأداء: مشرط / مياه / صنفرة + وردية + هالك جودة + شغل بدون إنترنت)
-- نفس نظام تسجيل الصب اليدوي لكن «الأداء» بدل «الصنف» ومن غير طلبيات.
-- شغّله مرة واحدة من Supabase -> SQL Editor -> New query -> Run (آمن لو اتشغّل أكتر من مرة)
-- محتاج setup_v2.sql و setup_security.sql و setup_owner_readonly.sql و setup_v4_4.sql يكونوا اتشغّلوا قبله.
-- بعده: شغّل setup_backup.sql تاني (عشان النسخ الاحتياطي يشمل الفنش).
-- بعده: من «المستخدمين» حدّد قسم «الفنش» للعمال/المسؤولين.
-- =====================================================================

-- 1) جدول سجل الفنش
create table if not exists public.finish_log (
  id          bigint generated by default as identity primary key,
  finish_date date        not null default current_date,
  task        text        not null,
  qty         integer     not null default 0,
  scrap       integer     not null default 0,
  shift       text,
  worker      text        check (worker is null or char_length(worker) <= 80),
  note        text        check (note   is null or char_length(note)   <= 300),
  client_id   uuid,
  created_by  uuid        default auth.uid(),
  created_at  timestamptz not null default now(),
  constraint finish_log_task_chk  check (task in ('مشرط','مياه','صنفرة')),
  constraint finish_log_shift_chk check (shift is null or shift in ('صباحي','مسائي','ليلي')),
  constraint finish_log_scrap_chk check (scrap >= 0 and scrap <= 100000),
  -- عدد القطع ممكن يبقى 0 لو التسجيل كله هالك (بشرط إن القطع + الهالك أكبر من صفر)
  constraint finish_log_qty_scrap_chk check (qty >= 0 and qty <= 100000 and qty + scrap > 0)
);
create index if not exists finish_log_date_idx on public.finish_log (finish_date);
create index if not exists finish_log_task_idx on public.finish_log (task);
-- client_id: عشان التسجيل اللي اتحفظ على الجهاز من غير نت ما يتكررش لو اتبعت مرتين
create unique index if not exists finish_log_client_id_uidx on public.finish_log (client_id) where client_id is not null;

-- 2) الأمان (RLS): القراءة والإضافة لأعضاء القسم. التعديل والحذف: المدير ومسؤول القسم في أي وقت،
--    ومسجّل الإنتاج في تسجيلاته هو وفي نفس اليوم بس.
alter table public.finish_log enable row level security;
drop policy if exists finish_select on public.finish_log;
drop policy if exists finish_insert on public.finish_log;
drop policy if exists finish_update on public.finish_log;
drop policy if exists finish_delete on public.finish_log;
create policy finish_select on public.finish_log for select to authenticated
  using ((select public.can_section('finish')));
create policy finish_insert on public.finish_log for insert to authenticated
  with check (
    (select public.can_section('finish'))
    and (created_by is null or created_by = auth.uid())
    and ((select public.can_manage_section('finish'))
         or finish_date = left(public.server_today()::text, 10)::date)
  );
create policy finish_update on public.finish_log for update to authenticated
  using (
    (select public.can_manage_section('finish'))
    or ((select public.can_section('finish')) and created_by = auth.uid()
        and finish_date = left(public.server_today()::text, 10)::date)
  )
  with check (
    (select public.can_manage_section('finish'))
    or ((select public.can_section('finish')) and created_by = auth.uid()
        and finish_date = left(public.server_today()::text, 10)::date)
  );
create policy finish_delete on public.finish_log for delete to authenticated
  using (
    (select public.can_manage_section('finish'))
    or ((select public.can_section('finish')) and created_by = auth.uid()
        and finish_date = left(public.server_today()::text, 10)::date)
  );
revoke all on public.finish_log from anon;
grant select, insert, update, delete on public.finish_log to authenticated;

-- 3) صاحب المصنع: عرض فقط
drop policy if exists owner_ro_ins on public.finish_log;
drop policy if exists owner_ro_upd on public.finish_log;
drop policy if exists owner_ro_del on public.finish_log;
create policy owner_ro_ins on public.finish_log as restrictive for insert to authenticated with check (not (select public.is_owner()));
create policy owner_ro_upd on public.finish_log as restrictive for update to authenticated using (not (select public.is_owner())) with check (not (select public.is_owner()));
create policy owner_ro_del on public.finish_log as restrictive for delete to authenticated using (not (select public.is_owner()));

-- 4) المدير «يشوف الكل» (view_all): قراءة فقط
drop policy if exists view_all_sel on public.finish_log;
create policy view_all_sel on public.finish_log for select to authenticated using ((select public.can_view_all()));

-- 5) سجل النشاط: ننسخ نفس الـ triggers اللي على repair_log (لو موجودة) عشان عمليات الفنش تظهر في «سجل النشاط»
do $$
declare r record; def text; t text := 'finish_log';
begin
  if to_regclass('public.repair_log') is null then return; end if;
  for r in
    select g.tgname, pg_get_triggerdef(g.oid) as d
      from pg_trigger g
     where g.tgrelid = 'public.repair_log'::regclass and not g.tgisinternal
  loop
    def := replace(r.d, 'repair_log', t);
    execute format('drop trigger if exists %I on public.%I', replace(r.tgname, 'repair_log', t), t);
    execute def;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

notify pgrst, 'reload schema';
