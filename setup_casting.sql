-- 1) جدول سجل الصب اليدوي
create table if not exists public.casting_log (
  id          bigint generated by default as identity primary key,
  casting_date date        not null default current_date,
  item        text,
  qty         integer     not null check (qty > 0 and qty <= 100000),
  worker      text        check (worker is null or char_length(worker) <= 80),
  note        text        check (note   is null or char_length(note)   <= 300),
  created_by  uuid        default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists casting_log_date_idx on public.casting_log (casting_date);

-- 2) الأمان (RLS)
--    القراءة والإضافة: أعضاء القسم والمدير.
--    التعديل والحذف: المدير ومسؤول القسم في أي وقت، ومسجّل الإنتاج في تسجيلاته هو وفي نفس اليوم بس.
alter table public.casting_log enable row level security;

drop policy if exists sec_all        on public.casting_log;
drop policy if exists cast_select    on public.casting_log;
drop policy if exists cast_insert    on public.casting_log;
drop policy if exists cast_update    on public.casting_log;
drop policy if exists cast_delete    on public.casting_log;

create policy cast_select on public.casting_log for select to authenticated
  using ((select public.can_section('casting')));

create policy cast_insert on public.casting_log for insert to authenticated
  with check (
    (select public.can_section('casting'))
    and (created_by is null or created_by = auth.uid())
    and ((select public.can_manage_section('casting'))
         or casting_date = left(public.server_today()::text, 10)::date)
  );

create policy cast_update on public.casting_log for update to authenticated
  using (
    (select public.can_manage_section('casting'))
    or ((select public.can_section('casting')) and created_by = auth.uid()
        and casting_date = left(public.server_today()::text, 10)::date)
  )
  with check (
    (select public.can_manage_section('casting'))
    or ((select public.can_section('casting')) and created_by = auth.uid()
        and casting_date = left(public.server_today()::text, 10)::date)
  );

create policy cast_delete on public.casting_log for delete to authenticated
  using (
    (select public.can_manage_section('casting'))
    or ((select public.can_section('casting')) and created_by = auth.uid()
        and casting_date = left(public.server_today()::text, 10)::date)
  );

revoke all on public.casting_log from anon;
grant select, insert, update, delete on public.casting_log to authenticated;

-- 3) سجل النشاط: ننسخ نفس الـ trigger اللي على repair_log (لو موجود) عشان عمليات الصب تظهر في «سجل النشاط»
do $$
declare r record; def text;
begin
  if to_regclass('public.repair_log') is null then return; end if;
  for r in
    select t.tgname, pg_get_triggerdef(t.oid) as d
      from pg_trigger t
     where t.tgrelid = 'public.repair_log'::regclass and not t.tgisinternal
  loop
    def := replace(r.d, 'repair_log', 'casting_log');
    execute format('drop trigger if exists %I on public.casting_log', replace(r.tgname, 'repair_log', 'casting_log'));
    execute def;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

notify pgrst, 'reload schema';

