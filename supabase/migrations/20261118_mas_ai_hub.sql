-- MAS AI HUB — إعدادات وسجلات الذكاء الاصطناعي + دالة الحقائق المجمّعة
-- آمن لإعادة التشغيل (idempotent). لا يحذف ولا يعدّل أي جدول إنتاج أو طلبيات.

-- ---------- 0) مساعدات صلاحيات ----------
create or replace function public.ai_is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles p
    where p.id = auth.uid() and coalesce(p.active, true) and p.role = 'admin');
$$;
revoke all on function public.ai_is_admin() from public;
grant execute on function public.ai_is_admin() to authenticated;

-- ---------- 1) الإعدادات (صف واحد فقط) ----------
create table if not exists public.ai_settings (
  id               smallint primary key default 1 check (id = 1),
  enabled          boolean  not null default true,
  primary_provider text     not null default 'gemini'  check (primary_provider  ~ '^[a-z0-9_]{2,20}$'),
  fallback_provider text    default 'groq'             check (fallback_provider ~ '^[a-z0-9_]{2,20}$'),
  auto_failover    boolean  not null default true,
  timeout_ms       integer  not null default 20000 check (timeout_ms between 3000 and 60000),
  daily_limit_user integer  not null default 30    check (daily_limit_user  between 1 and 1000),
  daily_limit_total integer not null default 300   check (daily_limit_total between 1 and 20000),
  updated_at       timestamptz not null default now(),
  updated_by       uuid,
  check (fallback_provider is null or fallback_provider <> primary_provider)
);
insert into public.ai_settings (id) values (1) on conflict (id) do nothing;

-- ---------- 2) السجلات ----------
create table if not exists public.ai_usage_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid, task text, provider text, model text,
  status text not null check (status in ('ok','error','blocked','quota')),
  latency_ms integer, prompt_chars integer, response_chars integer, failover boolean not null default false
);
create index if not exists ai_usage_log_day_idx on public.ai_usage_log (created_at desc);
create index if not exists ai_usage_log_user_idx on public.ai_usage_log (user_id, created_at desc);

create table if not exists public.ai_error_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid, provider text, error_class text, http_status integer, message text
);
create index if not exists ai_error_log_idx on public.ai_error_log (created_at desc);

create table if not exists public.ai_failover_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid, from_provider text, to_provider text, reason text
);
create index if not exists ai_failover_log_idx on public.ai_failover_log (created_at desc);

-- ---------- 3) RLS: المدير فقط يقرأ؛ الكتابة في السجلات من الـ Edge Function (service role) فقط ----------
alter table public.ai_settings     enable row level security;
alter table public.ai_usage_log    enable row level security;
alter table public.ai_error_log    enable row level security;
alter table public.ai_failover_log enable row level security;

do $$ declare t text; begin
  foreach t in array array['ai_settings','ai_usage_log','ai_error_log','ai_failover_log'] loop
    execute format('drop policy if exists %I on public.%I', t||'_admin_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.ai_is_admin())', t||'_admin_select', t);
  end loop;
end $$;
drop policy if exists ai_settings_admin_update on public.ai_settings;
create policy ai_settings_admin_update on public.ai_settings for update to authenticated
  using (public.ai_is_admin()) with check (public.ai_is_admin());

revoke all on public.ai_settings, public.ai_usage_log, public.ai_error_log, public.ai_failover_log from anon, authenticated;
grant select on public.ai_settings, public.ai_usage_log, public.ai_error_log, public.ai_failover_log to authenticated;
grant update (enabled, primary_provider, fallback_provider, auto_failover, timeout_ms, daily_limit_user, daily_limit_total)
  on public.ai_settings to authenticated;

create or replace function public.ai_settings_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); new.updated_by := auth.uid(); return new; end $$;
drop trigger if exists trg_ai_settings_touch on public.ai_settings;
create trigger trg_ai_settings_touch before update on public.ai_settings
  for each row execute function public.ai_settings_touch();

-- ---------- 4) الحقائق المجمّعة (الحساب هنا، لا في النموذج) ----------
-- security invoker: تُطبَّق RLS الخاصة بالمستخدم الذي يسأل، فلا يرى إلا ما يحق له.
-- تعتمد على search_item_report الموجودة (أعمدتها مؤكدة) فلا تكرار لأي بيانات.
create or replace function public.mas_ai_facts(
  p_from date, p_to date, p_secs text[] default null)
returns jsonb language plpgsql stable security invoker set search_path = public as $$
declare v jsonb;
begin
  if p_from is null or p_to is null or p_to < p_from or p_to - p_from > 366 then
    raise exception 'bad period';
  end if;
  with r as (
    select e->>'s' sec, e->>'k' kind, (e->>'d')::date d, e->>'item' item,
           e->>'sub' sub, coalesce((e->>'qty')::numeric,0) qty,
           coalesce((e->>'good')::numeric,0) good
    from jsonb_array_elements(coalesce(
      public.search_item_report('', 'part', p_from, p_to, p_secs)->'rows','[]'::jsonb)) e
  ),
  prod as (select sec, sum(qty) total, count(*) entries, count(distinct d) active_days
           from r where kind='p' group by sec),
  waste as (select sec, sum(qty) waste_qty, sum(good) good_qty from r where kind='w' group by sec),
  daily as (select d, sec, sum(qty) q from r where kind='p' group by d, sec),
  top_items as (
    select sec, item, sum(qty) q,
           row_number() over (partition by sec order by sum(qty) desc) rn
    from r where kind='p' group by sec, item),
  colors as (
    select sec, sub color, sum(qty) q,
           row_number() over (partition by sec order by sum(qty) desc) rn
    from r where kind='p' and sub <> '' and sec in ('glaze','spray','deco') group by sec, sub),
  waste_items as (
    select sec, item, sum(qty) q,
           row_number() over (partition by sec order by sum(qty) desc) rn
    from r where kind='w' group by sec, item)
  select jsonb_build_object(
    'period', jsonb_build_object('from', p_from, 'to', p_to),
    'production_by_section', coalesce((select jsonb_agg(to_jsonb(prod) order by total desc) from prod),'[]'),
    'waste_by_section', coalesce((select jsonb_agg(jsonb_build_object(
        'sec', w.sec, 'waste_qty', w.waste_qty, 'good_qty', w.good_qty,
        'waste_pct_of_production', case when coalesce(p.total,0) > 0 then round(100*w.waste_qty/p.total, 2) end))
        from waste w left join prod p using (sec)),'[]'),
    'daily_production', coalesce((select jsonb_agg(jsonb_build_object('d',d,'sec',sec,'q',q) order by d) from daily),'[]'),
    'top_items', coalesce((select jsonb_agg(jsonb_build_object('sec',sec,'item',item,'q',q)) from top_items where rn<=10),'[]'),
    'top_colors', coalesce((select jsonb_agg(jsonb_build_object('sec',sec,'color',color,'q',q)) from colors where rn<=10),'[]'),
    'top_waste_items', coalesce((select jsonb_agg(jsonb_build_object('sec',sec,'item',item,'q',q)) from waste_items where rn<=10),'[]')
  ) into v;
  return v;
end $$;
revoke all on function public.mas_ai_facts(date, date, text[]) from public;
grant execute on function public.mas_ai_facts(date, date, text[]) to authenticated;
