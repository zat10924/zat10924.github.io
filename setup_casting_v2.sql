-- 1) جدول طلبيات الصب
create table if not exists public.casting_orders (
  id           bigint generated by default as identity primary key,
  title        text   check (title is null or char_length(title) <= 120),   -- اسم العميل / عنوان الطلبية (اختياري)
  item         text   not null check (char_length(item) between 1 and 120),
  qty_required integer not null check (qty_required > 0 and qty_required <= 1000000),
  order_date   date   not null default current_date,
  due_date     date,
  status       text   not null default 'open' check (status in ('open','closed')),
  note         text   check (note is null or char_length(note) <= 300),
  created_by   uuid   default auth.uid(),
  created_at   timestamptz not null default now()
);
create index if not exists casting_orders_status_idx on public.casting_orders (status);

alter table public.casting_orders enable row level security;
drop policy if exists co_select on public.casting_orders;
drop policy if exists co_insert on public.casting_orders;
drop policy if exists co_update on public.casting_orders;
drop policy if exists co_delete on public.casting_orders;
create policy co_select on public.casting_orders for select to authenticated
  using ((select public.can_section('casting')));
create policy co_insert on public.casting_orders for insert to authenticated
  with check ((select public.can_manage_section('casting')));
create policy co_update on public.casting_orders for update to authenticated
  using ((select public.can_manage_section('casting'))) with check ((select public.can_manage_section('casting')));
create policy co_delete on public.casting_orders for delete to authenticated
  using ((select public.can_manage_section('casting')));
revoke all on public.casting_orders from anon;
grant select, insert, update, delete on public.casting_orders to authenticated;

-- 2) أعمدة جديدة في سجل الصب: الوردية + هالك الجودة + ربط بالطلبية (الفاضي = بدون طلبية)
alter table public.casting_log add column if not exists shift    text;
alter table public.casting_log add column if not exists scrap    integer not null default 0;
alter table public.casting_log add column if not exists order_id bigint references public.casting_orders(id) on delete set null;
create index if not exists casting_log_order_idx on public.casting_log (order_id);

alter table public.casting_log drop constraint if exists casting_log_shift_chk;
alter table public.casting_log add  constraint casting_log_shift_chk check (shift is null or shift in ('صباحي','مسائي','ليلي'));
alter table public.casting_log drop constraint if exists casting_log_scrap_chk;
alter table public.casting_log add  constraint casting_log_scrap_chk check (scrap >= 0 and scrap <= 100000);

-- عدد القطع ممكن يبقى 0 لو التسجيل كله هالك (بشرط إن القطع + الهالك أكبر من صفر)
alter table public.casting_log drop constraint if exists casting_log_qty_check;
alter table public.casting_log drop constraint if exists casting_log_qty_scrap_chk;
alter table public.casting_log add  constraint casting_log_qty_scrap_chk check (qty >= 0 and qty <= 100000 and qty + scrap > 0);

-- 3) سجل النشاط على جدول الطلبيات (نفس trigger جدول casting_log لو موجود)
do $$
declare r record; def text;
begin
  for r in
    select t.tgname, pg_get_triggerdef(t.oid) as d
      from pg_trigger t
     where t.tgrelid = 'public.casting_log'::regclass and not t.tgisinternal
  loop
    def := replace(r.d, 'casting_log', 'casting_orders');
    execute format('drop trigger if exists %I on public.casting_orders', replace(r.tgname, 'casting_log', 'casting_orders'));
    execute def;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

notify pgrst, 'reload schema';
