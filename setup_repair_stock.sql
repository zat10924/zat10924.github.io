-- setup_repair_stock.sql — جرد التصليح (كام قطعة عندي في التصليح من كل صنف)
-- الفكرة: كل مرة تضيف قطع للتصليح بتتسجل هنا (وارد) أو تسوية جرد،
-- والمتبقي = مجموع الوارد − كمية التصليح المسجلة في repair_log لنفس الصنف.
-- يعني لما تسجّل تصليح الخصم بيحصل لوحده، من غير أي ربط يدوي.
-- شغّله مرة واحدة من Supabase -> SQL Editor -> Run (آمن لو اتشغّل أكتر من مرة)
-- بعده: شغّل setup_backup.sql تاني عشان النسخ الاحتياطي يشمل الجرد.
-- =====================================================================

create table if not exists public.repair_stock (
  id          bigint generated by default as identity primary key,
  stock_date  date        not null default current_date,
  item        text        not null check (char_length(btrim(item)) between 1 and 120),
  qty         integer     not null check (qty <> 0 and qty between -100000 and 100000),
  kind        text        not null default 'in' check (kind in ('in','adjust')),
  note        text        check (note is null or char_length(note) <= 300),
  client_id   uuid,
  created_by  uuid        default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists repair_stock_item_idx on public.repair_stock (lower(btrim(item)));
create index if not exists repair_stock_date_idx on public.repair_stock (stock_date);
create unique index if not exists repair_stock_client_id_uidx on public.repair_stock (client_id) where client_id is not null;

alter table public.repair_stock enable row level security;
drop policy if exists rstock_select on public.repair_stock;
drop policy if exists rstock_insert on public.repair_stock;
drop policy if exists rstock_update on public.repair_stock;
drop policy if exists rstock_delete on public.repair_stock;
create policy rstock_select on public.repair_stock for select to authenticated
  using ((select public.can_section('repair')));
create policy rstock_insert on public.repair_stock for insert to authenticated
  with check ((select public.can_section('repair')) and (created_by is null or created_by = auth.uid()));
create policy rstock_update on public.repair_stock for update to authenticated
  using ((select public.can_manage_section('repair')) or ((select public.can_section('repair')) and created_by = auth.uid() and stock_date = left(public.server_today()::text, 10)::date))
  with check ((select public.can_manage_section('repair')) or ((select public.can_section('repair')) and created_by = auth.uid() and stock_date = left(public.server_today()::text, 10)::date));
create policy rstock_delete on public.repair_stock for delete to authenticated
  using ((select public.can_manage_section('repair')) or ((select public.can_section('repair')) and created_by = auth.uid() and stock_date = left(public.server_today()::text, 10)::date));
revoke all on public.repair_stock from anon;
grant select, insert, update, delete on public.repair_stock to authenticated;

-- صاحب المصنع: عرض فقط
drop policy if exists owner_ro_ins on public.repair_stock;
drop policy if exists owner_ro_upd on public.repair_stock;
drop policy if exists owner_ro_del on public.repair_stock;
create policy owner_ro_ins on public.repair_stock as restrictive for insert to authenticated with check (not (select public.is_owner()));
create policy owner_ro_upd on public.repair_stock as restrictive for update to authenticated using (not (select public.is_owner())) with check (not (select public.is_owner()));
create policy owner_ro_del on public.repair_stock as restrictive for delete to authenticated using (not (select public.is_owner()));

-- المدير «يشوف الكل»: قراءة فقط
drop policy if exists view_all_sel on public.repair_stock;
create policy view_all_sel on public.repair_stock for select to authenticated using ((select public.can_view_all()));

-- سجل النشاط: نفس triggers جدول repair_log
do $$
declare r record; def text; t text := 'repair_stock';
begin
  if to_regclass('public.repair_log') is null then return; end if;
  for r in select g.tgname, pg_get_triggerdef(g.oid) as d from pg_trigger g
            where g.tgrelid = 'public.repair_log'::regclass and not g.tgisinternal
  loop
    def := replace(r.d, 'repair_log', t);
    execute format('drop trigger if exists %I on public.%I', replace(r.tgname, 'repair_log', t), t);
    execute def;
  end loop;
exception when others then
  raise notice 'تخطّيت ربط سجل النشاط: %', sqlerrm;
end $$;

notify pgrst, 'reload schema';
